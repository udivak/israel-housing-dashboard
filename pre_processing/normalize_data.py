def ensure_indexes():
    DST_COL.create_index("source_id", unique=True)
    DST_COL.create_index("city_id")
    DST_COL.create_index("transaction_date")
    DST_COL.create_index([("lat", ASCENDING), ("lon", ASCENDING)])

def run():
    print("🔌 Connecting...")
    ensure_indexes()

    sources = [s for s in NORMALIZERS.keys()]
    total_written = 0
    total_skipped = 0

    for source in sources:
        print(f"\n📥 Processing {source}...")
        cursor = SRC_COL.find(
            {"source_name": source},
            {"_id": 1, "source_name": 1, "raw_payload": 1, "geometry": 1}
        )

        batch   = []
        count   = 0
        skipped = 0
        normalizer = NORMALIZERS[source]

        for doc in cursor:
            try:
                row = normalizer(doc)
            except Exception as e:
                skipped += 1
                continue

            # price חובה
            if row["price"] is None:
                skipped += 1
                continue

            # חשב price_per_sqm אם חסר
            if row["price_per_sqm"] is None and row["price"] and row["area_sqm"]:
                row["price_per_sqm"] = round(row["price"] / row["area_sqm"], 2)

            batch.append(UpdateOne(
                {"source_id": row["source_id"]},
                {"$set": row},
                upsert=True
            ))
            count += 1

            if len(batch) >= BATCH_SIZE:
                try:
                    DST_COL.bulk_write(batch, ordered=False)
                except BulkWriteError:
                    pass
                batch = []
                print(f"   {count:>8,} written...", end="\r")

        if batch:
            try:
                DST_COL.bulk_write(batch, ordered=False)
            except BulkWriteError:
                pass

        total_written += count
        total_skipped += skipped
        print(f"   ✅ {source:<30} written={count:>7,}  skipped={skipped:>5,}")

    # ================================================================
    # REPORT
    # ================================================================
    print(f"\n{'='*60}")
    print(f"  DONE  |  total written: {total_written:,}  |  skipped: {total_skipped:,}")
    print(f"{'='*60}")

    total = DST_COL.count_documents({})
    print(f"\n📊 Collection stats ({total:,} docs total):")

    # null counts
    fields = ["price", "area_sqm", "price_per_sqm", "rooms", "floor",
              "year_built", "city_id", "city_name", "lat", "transaction_date"]
    print(f"\n  {'field':<20} {'null':>8}  {'%':>6}")
    print(f"  {'-'*20} {'-'*8}  {'-'*6}")
    for f in fields:
        n   = DST_COL.count_documents({f: None})
        pct = 100 * n / total if total else 0
        print(f"  {f:<20} {n:>8,}  {pct:>5.1f}%")

    # per source
    print("\n  Docs per source:")
    for src in sources:
        n = DST_COL.count_documents({"source": src})
        print(f"    {src:<30} {n:>8,}")

    # city_id coverage
    no_city = DST_COL.count_documents({"city_id": None})
    print(f"\n  city_id null: {no_city:,} ({100*no_city/total:.1f}%)")

if __name__ == "__main__":
    run()