def _floor(val):
    if val is None: return None
    s = str(val).strip()
    if s in FLOOR_MAP: return FLOOR_MAP[s]
    try: return int(float(s))
    except: return None

def _float(val):
    if val is None: return None
    if isinstance(val, (int, float)) and not np.isnan(float(val)): return float(val)
    try: return float(str(val).replace(",", "").strip())
    except: return None

def _int(val):
    f = _float(val)
    return int(f) if f is not None else None

def _str(val):
    if val is None: return None
    s = str(val).strip()
    return s if s else None

def _date_iso(val):
    if not val: return None
    s = str(val).strip().rstrip("Z").rstrip("z")
    try:
        dt = datetime.fromisoformat(s)
        return dt.replace(tzinfo=None)
    except: return None

def _date_ddmmyyyy(val):
    if not val: return None
    s = str(val).strip()
    try: return datetime.strptime(s, "%d.%m.%Y")
    except: return None

def _coords(geometry):
    """מחלץ [lon, lat] מ-GeoJSON Point"""
    if not geometry or geometry.get("type") != "Point":
        return None, None
    coords = geometry.get("coordinates", [])
    if len(coords) >= 2:
        return float(coords[0]), float(coords[1])
    return None, None

